"""Point old Tiki search links at the site's search page (see PLAN.md item 12).

Old pages link to /pages/search-results/ with the search term in the link text, e.g.
"Search VitaminDWiki for ICU OR “critical care”". This repoints them to
/search/?q=ICU+OR+"critical care" using data/search_link_fixes_0014.json (generated by the
link preview). The search page handles OR queries. Same safety rules as migration 0013:
a link changes only when target and text both match; originals are backed up; reversible.
"""

import json
from pathlib import Path

from django.db import migrations

from core.models import derive_content_fields
from helper_functions.link_fixes import apply_link_fixes, build_fix_map

BACKUP_REASON = 'search link fixes (migration 0014)'
FIXES_FILE = Path(__file__).resolve().parent / 'data' / 'search_link_fixes_0014.json'


def fix_links(apps, schema_editor):
    Page = apps.get_model('posts', 'Page')
    Backup = apps.get_model('posts', 'PageContentBackup')

    fixes_by_page = json.loads(FIXES_FILE.read_text(encoding='utf-8'))['fixes']
    pages_changed = links_changed = 0
    for slug, fixes in fixes_by_page.items():
        row = Page.objects.filter(slug=slug).values('id', 'content_md').first()
        if not row:
            continue
        new_md, count = apply_link_fixes(row['content_md'] or '', build_fix_map(fixes))
        if not count:
            continue
        Backup.objects.create(page_id=row['id'], content_md=row['content_md'], reason=BACKUP_REASON)
        content_html, content_text, character_count = derive_content_fields(new_md)
        Page.objects.filter(pk=row['id']).update(
            content_md=new_md,
            content_html=content_html,
            content_text=content_text,
            character_count=character_count,
        )
        pages_changed += 1
        links_changed += count
    print(f"\n  Search links: {links_changed} links repointed on {pages_changed} pages")


def restore_links(apps, schema_editor):
    Page = apps.get_model('posts', 'Page')
    Backup = apps.get_model('posts', 'PageContentBackup')

    restored = 0
    for backup in Backup.objects.filter(reason=BACKUP_REASON).order_by('-id'):
        content_html, content_text, character_count = derive_content_fields(backup.content_md)
        restored += Page.objects.filter(pk=backup.page_id).update(
            content_md=backup.content_md,
            content_html=content_html,
            content_text=content_text,
            character_count=character_count,
        )
    Backup.objects.filter(reason=BACKUP_REASON).delete()
    print(f"\n  Search link fixes reverted on {restored} pages")


class Migration(migrations.Migration):

    dependencies = [
        ('posts', '0013_fix_broken_links'),
    ]

    operations = [
        migrations.RunPython(fix_links, restore_links),
    ]
